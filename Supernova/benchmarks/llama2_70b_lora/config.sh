#!/bin/bash
LAYOUT=${LAYOUT:-tp1cp2}
COMMON="LOAD_CKPT=True CKPT_ROOT=$MODEL_DIR DATA_ROOT=$DATA_DIR SKIP_EVALS=3 PARALLEL_LOAD=True LOAD_THREADS=$(( $(nproc) / 2 )) FP8=True
  VAL_MBS=4 VAL_GBS=8 EVAL_PAD_MICROBATCH=1
  UB_SKIPMC=1 NCCL_UB=False
  TRAIN_LOSS_LOG_INTERVAL=1
  NCCL_MIN_CTAS=32 NCCL_MIN_P2P_NCHANNELS=32
  NCCL_NCHANNELS_PER_NET_PEER=32 NCCL_NVLS_ENABLE=1
  NVTE_FP8_DPA_BWD=1 NVTE_NORM_BWD_USE_CUDNN=1 NVTE_NORM_FWD_USE_CUDNN=1"

case $LAYOUT in
  tp1cp4)
RECIPE="TP=1 CP=4 MBS=2 MINIBS=2 CUDA_DEVICE_MAX_CONNECTIONS=1
  LR=0.0005 WARMUP_STEPS=0 LR_DECAY_STEPS=800 MAX_STEPS=800
  VAL_CHECK_INTERVAL=384 SKIP_EVALS=3
  FP8_AMAX_HISTORY=4 FP8_AMAX_ALGO=max FP8_REDUCE_AMAX=True USE_TE_OPS=1 FP8_ACT=1 LORA_A2A=1
  GRADIENT_ACCUMULATION_FUSION=True TMO=${TMO:-10800} STALL_S=300
  TP_COMM_OVERLAP=False DEEPGEMM=1 DEEPGEMM_NUM_SMS=128 NVTE_FAV3_FP8_BWD=1 NVTE_FAV3_FP8_FWD=1 LORA_EVAL_MERGE=1
  LORA_LOCAL=1 SWIGLU_FUSION=1 FP8_TRANSIENT_TRANSPOSE=1 CP_A2A_COMM=${CP_A2A_COMM:-ce} CP_SHARD_WEIGHTS=${CP_SHARD_WEIGHTS:-auto} NVTE_FUSED_POST_RS_NORM=1
  LOAD_GROUP_LAYERS=4 PARALLEL_LOAD=True NCCL_NVLS_ENABLE=0 EXPECT_GBS=8
  WT_RESIDENT_MLP=fc2:42 PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True"
    ;;
  tp2cp2)
RECIPE="TP=2 CP=2 MBS=2 MINIBS=2 CUDA_DEVICE_MAX_CONNECTIONS=1
  LR=0.0005 WARMUP_STEPS=0 LR_DECAY_STEPS=800 MAX_STEPS=800
  VAL_CHECK_INTERVAL=384 SKIP_EVALS=3
  FP8_AMAX_HISTORY=4 FP8_AMAX_ALGO=max FP8_REDUCE_AMAX=True USE_TE_OPS=1 FP8_ACT=1 LORA_A2A=1
  GRADIENT_ACCUMULATION_FUSION=True TMO=${TMO:-10800} STALL_S=300
  TP_COMM_OVERLAP=True DEEPGEMM=1 DEEPGEMM_NUM_SMS=128 NVTE_FAV3_FP8_BWD=1 NVTE_FAV3_FP8_FWD=1 LORA_EVAL_MERGE=1
  LORA_LOCAL=1 SWIGLU_FUSION=1 NVTE_CP_A2A_HEAD_CHUNKS=2 UB_FC1_FPROP_NUM_SM=4
  CP_A2A_COMM=${CP_A2A_COMM:-ce} FP8_TRANSIENT_TRANSPOSE=0 EXPECT_GBS=8"
    ;;
  tp1cp1)
RECIPE="TP=1 CP=1 MBS=1 MINIBS=1 VAL_MBS=1 CUDA_DEVICE_MAX_CONNECTIONS=1
  LR=0.0005 WARMUP_STEPS=0 LR_DECAY_STEPS=800 MAX_STEPS=800
  VAL_CHECK_INTERVAL=384 SKIP_EVALS=3
  FP8_AMAX_HISTORY=4 FP8_AMAX_ALGO=max FP8_REDUCE_AMAX=True USE_TE_OPS=1 FP8_ACT=1 LORA_A2A=1
  GRADIENT_ACCUMULATION_FUSION=True TMO=${TMO:-10800} STALL_S=300
  TP_COMM_OVERLAP=False DEEPGEMM=1 DEEPGEMM_NUM_SMS=128 NVTE_FAV3_FP8_BWD=1 NVTE_FAV3_FP8_FWD=1 LORA_EVAL_MERGE=1
  LORA_LOCAL=1 SWIGLU_FUSION=1 FP8_TRANSIENT_TRANSPOSE=1 NVTE_FUSED_POST_RS_NORM=1
  LOAD_GROUP_LAYERS=4 PARALLEL_LOAD=True NCCL_NVLS_ENABLE=0 EXPECT_GBS=8
  WT_RESIDENT_MLP= WT_RESIDENT_ATTN=0 RECOMPUTE_GRANULARITY=full RECOMPUTE_METHOD=block RECOMPUTE_NUM_LAYERS=24
  PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True"
    ;;
  tp1cp2)
_DP=$(( ${NGPUS:-8} / 2 ))
case $_DP in 4|8) ;; *) echo "config.sh: tp1cp2 needs 8 or 16 GPUs (NGPUS=${NGPUS:-8})" >&2; exit 1 ;; esac
_MB=$(( 8 / _DP )); _WU=0; [ "$_DP" -eq 8 ] && _WU=32
RECIPE="TP=1 CP=2 MBS=1 MINIBS=$_MB VAL_MBS=$_MB CUDA_DEVICE_MAX_CONNECTIONS=1
  LR=0.0005 WARMUP_STEPS=$_WU LR_DECAY_STEPS=800 MAX_STEPS=800
  VAL_CHECK_INTERVAL=384 SKIP_EVALS=3
  FP8_AMAX_HISTORY=4 FP8_AMAX_ALGO=max FP8_REDUCE_AMAX=True USE_TE_OPS=1 FP8_ACT=1 LORA_A2A=1
  GRADIENT_ACCUMULATION_FUSION=True TMO=${TMO:-10800} STALL_S=300
  TP_COMM_OVERLAP=False DEEPGEMM=1 DEEPGEMM_NUM_SMS=128 NVTE_FAV3_FP8_BWD=1 NVTE_FAV3_FP8_FWD=1 LORA_EVAL_MERGE=1
  LORA_LOCAL=1 SWIGLU_FUSION=1 FP8_TRANSIENT_TRANSPOSE=1 CP_A2A_COMM=${CP_A2A_COMM:-ce} CP_SHARD_WEIGHTS=${CP_SHARD_WEIGHTS:-auto} NVTE_FUSED_POST_RS_NORM=1
  LOAD_GROUP_LAYERS=4 PARALLEL_LOAD=True NCCL_NVLS_ENABLE=0 EXPECT_GBS=8
  WT_RESIDENT_MLP=fc2:42 PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True"
    ;;
  *) echo "config.sh: LAYOUT=$LAYOUT (tp1cp4 | tp2cp2 | tp1cp1 | tp1cp2)" >&2; exit 1 ;;
esac

export MLPERF_SUBMISSION_ORG="Nanyang Technological University"
export MLPERF_SUBMISSION_PLATFORM=${MLPERF_SUBMISSION_PLATFORM:-Supernova}
